export const auditActionCodes = Object.freeze(
  Object.keys(actionMessages) as Array<keyof typeof actionMessages>,
)
export const auditTargetTypeCodes = Object.freeze(
  Object.keys(targetTypeMessages) as Array<keyof typeof targetTypeMessages>,
)
export const auditResultCodes = Object.freeze(
  Object.keys(resultMessages) as Array<keyof typeof resultMessages>,
)

export type AuditTranslationKind = "actions" | "targetTypes" | "results"

const messagesByKind = {
  actions: actionMessages,
  targetTypes: targetTypeMessages,
  results: resultMessages,
} satisfies Record<AuditTranslationKind, AuditMessages>

function resourceCode(code: string): string {
  return code.replaceAll(".", "__dot__")
}

export function auditTranslationKey(
  kind: AuditTranslationKind,
  code: string,
): string {
  return `auditValues.${kind}.${resourceCode(code)}`
}

export function auditTranslationResource(locale: Locale): {
  actions: Record<string, string>
  targetTypes: Record<string, string>
  results: Record<string, string>
} {
  const localeIndex = locale === "zh-CN" ? 0 : 1
  return Object.fromEntries(
    Object.entries(messagesByKind).map(([kind, messages]) => [
      kind,
      Object.fromEntries(
        Object.entries(messages).map(([code, message]) => [
          resourceCode(code),
          message[localeIndex],
        ]),
      ),
    ]),
  ) as {
    actions: Record<string, string>
    targetTypes: Record<string, string>
    results: Record<string, string>
  }
}

export function auditFlatTranslations(locale: Locale): Record<string, string> {
  const resource = auditTranslationResource(locale)
  return Object.fromEntries(
    Object.entries(resource).flatMap(([kind, messages]) =>
      Object.entries(messages).map(([code, message]) => [
        `auditValues.${kind}.${code}`,
        message,
      ]),
    ),
  )
}
